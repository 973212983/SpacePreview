export const sourceLanguages: Record<string, string> = Object.fromEntries(
  Object.entries(groups).flatMap(([language, aliases]) =>
    aliases.split(' ').map((ext) => [ext, language]),
  ),
);
export function sourceLanguage(name: string): string {
  const base = name.split(/[\\/]/).pop()!.toLowerCase();
  if (base === 'cmakelists.txt') return 'cmake';
  if (/^(dockerfile|containerfile)(\.|$)/.test(base)) return 'dockerfile';
  if (/^\.env(\.|$)/.test(base)) return 'ini';
  return sourceLanguages[base] ?? sourceLanguages[base.split('.').pop()!] ?? 'plaintext';
}
